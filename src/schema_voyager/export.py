"""Publish a finished run: copy its results table, episode traces and store
snapshots into the tracked results/ folder, and write the numbers and the
example trace that the field guide (site/dist) shows."""

from __future__ import annotations

import json
import shutil
import time
from pathlib import Path
from typing import Any

from .evaluator import summary_rows
from .models import EpisodeResult

SITE_DATA = Path("site/dist/results.js")
_COPIED = ("results.md", "results.json", "store_D_*.json", "skills_*.json", "episodes/*.jsonl")


def export_run(run_dir: Path, note: str = "", out_dir: Path = Path("results"), site_data: Path = SITE_DATA) -> None:
    """`note` records anything a reader must know about the run, such as an episode that was rerun."""
    results = [EpisodeResult(**raw) for raw in json.loads((run_dir / "results.json").read_text(encoding="utf-8"))]
    commit = _run_commit(run_dir)
    exported = time.strftime("%Y-%m-%d %H:%M")

    for pattern in _COPIED:
        for old in out_dir.glob(pattern):
            old.unlink()
        for source in sorted(run_dir.glob(pattern)):
            target = out_dir / source.relative_to(run_dir)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
    readme = [
        "# Results",
        "",
        f"Copied from `runs/{run_dir.name}` (code commit `{commit}`) by `schema-voyager export` on {exported}.",
        "",
        *([f"Note: {note}", ""] if note else []),
        "- `results.md`: the results table; `results.json`: one record per episode",
        "- `episodes/*.jsonl`: every plan, step, prediction, observation, contradiction and revision; "
        "replay them with `schema-voyager panel`",
        "- `store_D_*.json`: D's schema store before training, after one episode, after training, and after the holdout",
        "- `skills_*.json`: the baselines' skill libraries",
    ]
    (out_dir / "README.md").write_text("\n".join(readme) + "\n", encoding="utf-8")

    data = {
        "run": run_dir.name,
        "commit": commit,
        "exported": exported,
        "note": note,
        "rows": summary_rows(results),
        "trace": _example_trace(run_dir, results),
        "rule": _rule_with_evidence(run_dir / "store_D_2_after_training.json", "mine_coal_ore"),
        "skill": _find(run_dir / "store_D_3_after_holdout.json", "skills", "skill_torch"),
    }
    site_data.write_text(
        "// Generated by `schema-voyager export`; do not edit.\n"
        f"window.SCHEMA_VOYAGER_RESULTS = {json.dumps(data, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"Exported runs/{run_dir.name} (commit {commit}) to {out_dir}/ and {site_data}")


def _run_commit(run_dir: Path) -> str:
    path = run_dir / "COMMIT"
    return path.read_text(encoding="utf-8").strip() if path.exists() else "unknown"


def _example_trace(run_dir: Path, results: list[EpisodeResult]) -> dict[str, Any] | None:
    """D's H3 episode on the first holdout layout: the story the demo tells."""
    seeds = sorted(r.layout_seed for r in results if r.system == "D" and r.task_id == "h3")
    if not seeds:
        return None
    path = run_dir / "episodes" / f"D_h3_L{seeds[0]}.jsonl"
    events = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    return {"layout": seeds[0], "events": events}


def _rule_with_evidence(store_path: Path, rule_id: str) -> dict[str, Any] | None:
    rule = _find(store_path, "rules", rule_id)
    if rule is None:
        return None
    confirmed = rule["evidence"]["confirmed"]
    # Transition ids are "<episode id>/<action index>".
    episodes = {transition.rsplit("/", 1)[0] for transition in confirmed}
    return {**rule, "confirmations": len(confirmed), "episodes": len(episodes)}


def _find(store_path: Path, kind: str, item_id: str) -> dict[str, Any] | None:
    if not store_path.exists():
        return None
    items = json.loads(store_path.read_text(encoding="utf-8"))[kind]
    return next((item for item in items if item["id"] == item_id), None)
